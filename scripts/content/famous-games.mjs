const data = games.map(
  ([
    id,
    title,
    white,
    black,
    year,
    event,
    result,
    motif,
    source,
    score,
    intro,
    notes,
  ]) => {
    const c = new Chess();
    try {
      c.loadPgn(score + " " + result);
    } catch (e) {
      throw new Error(id + ": " + e.message);
    }
    const h = c.history({ verbose: true });
    for (const n of Object.keys(notes))
      if (+n > h.length) throw new Error(id + " bad note " + n);
    c.setHeader("Event", event);
    c.setHeader("White", white);
    c.setHeader("Black", black);
    c.setHeader("Date", year + ".??.??");
    c.setHeader("Result", result);
    return {
      id,
      title,
      white,
      black,
      year,
      event,
      result,
      motif,
      source: "https://en.wikipedia.org/wiki/" + source,
      intro,
      moves: h.map((m) => m.from + m.to + (m.promotion || "")),
      notation: h.map((m) => m.san),
      positions: [h[0].before, ...h.map((m) => m.after)],
      notes,
      pgn: c.pgn(),
    };
  },
);
writeFileSync(
  "public/data/famous-games.json",
  JSON.stringify(data, null, 2) + "\n",
);
