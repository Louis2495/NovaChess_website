function parse(text) {
  const c = new Chess();
  for (const m of text.split(" ").filter(Boolean))
    try {
      c.move(m);
    } catch (e) {
      throw Error(text + " : " + m + " " + e.message);
    }
  return c
    .history({ verbose: true })
    .map((m) => m.from + m.to + (m.promotion || ""));
}
const data = rows.map(
  ([id, name, opening, setup, trap, refutation, why, defense, lesson]) => {
    const base = parse(setup),
      bad = parse(setup + " " + trap),
      good = parse(setup + " " + refutation);
    return {
      id,
      name,
      opening,
      setup: base,
      trap: bad,
      refutation: good,
      why,
      defense,
      lesson,
    };
  },
);
writeFileSync(
  "public/data/opening-traps.json",
  JSON.stringify(data, null, 2) + "\n",
);
